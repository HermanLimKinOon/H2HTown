-- Local development schema baseline for tables referenced by the existing
-- migrations. Column definitions follow the checked-in CSV headers and the
-- application's queries. Member CSV rows are deliberately not copied here.

CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  badge text,
  image text,
  specs jsonb NOT NULL DEFAULT '[]'::jsonb,
  active boolean NOT NULL DEFAULT true,
  gallery jsonb NOT NULL DEFAULT '[]'::jsonb,
  category text,
  created_at timestamptz NOT NULL DEFAULT now(),
  description text,
  member_price integer,
  original_price integer,
  live_recommended boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.lessons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  week integer,
  title text NOT NULL,
  r2_key text,
  course_id bigint NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  lesson_order integer
);

CREATE TABLE IF NOT EXISTS public.members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area text,
  name text NOT NULL,
  tier text NOT NULL DEFAULT 'Member',
  email text,
  phone text,
  gender text,
  user_id uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  birth_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  postal_code text,
  referred_by bigint REFERENCES public.members(id) ON DELETE SET NULL,
  address_line text,
  referral_code text UNIQUE,
  phone_verified boolean NOT NULL DEFAULT false,
  phone_country_code text,
  referral_bonus_paid boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX IF NOT EXISTS members_email_lower_key
  ON public.members (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.member_wallets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint NOT NULL UNIQUE REFERENCES public.members(id) ON DELETE CASCADE,
  points_balance integer NOT NULL DEFAULT 0,
  muslim_donation_total integer NOT NULL DEFAULT 0,
  total_spent_this_year integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.member_point_transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,
  member_id bigint NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  description text,
  amount_spent integer NOT NULL DEFAULT 0,
  points_earned integer NOT NULL DEFAULT 0,
  donation_amount integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.member_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  amount integer NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  item_id integer NOT NULL,
  item_name text NOT NULL,
  member_id bigint NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  order_type text NOT NULL
);

CREATE INDEX IF NOT EXISTS lessons_course_order_idx
  ON public.lessons (course_id, lesson_order, id);
CREATE INDEX IF NOT EXISTS member_orders_member_created_idx
  ON public.member_orders (member_id, created_at DESC);
CREATE INDEX IF NOT EXISTS member_point_transactions_member_created_idx
  ON public.member_point_transactions (member_id, created_at DESC);

-- Enable row security before the grant and policy migrations are applied.
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.member_wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.member_point_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.member_orders ENABLE ROW LEVEL SECURITY;

-- Public catalog reads. The later admin-write migrations add admin-only
-- management policies to products, courses, and lessons.
DROP POLICY IF EXISTS products_public_read ON public.products;
CREATE POLICY products_public_read ON public.products
  FOR SELECT TO anon, authenticated USING (active);

DROP POLICY IF EXISTS lessons_public_read ON public.lessons;
CREATE POLICY lessons_public_read ON public.lessons
  FOR SELECT TO anon, authenticated USING (true);

-- Member-scoped read policies. Later security migrations tighten the member
-- policies and remove direct wallet / points writes.
DROP POLICY IF EXISTS members_read_own ON public.members;
CREATE POLICY members_read_own ON public.members
  FOR SELECT TO authenticated
  USING (user_id = auth.uid());

DROP POLICY IF EXISTS member_wallets_read_own ON public.member_wallets;
CREATE POLICY member_wallets_read_own ON public.member_wallets
  FOR SELECT TO authenticated
  USING (member_id IN (
    SELECT id FROM public.members WHERE user_id = auth.uid()
  ));

DROP POLICY IF EXISTS member_point_transactions_read_own ON public.member_point_transactions;
CREATE POLICY member_point_transactions_read_own ON public.member_point_transactions
  FOR SELECT TO authenticated
  USING (member_id IN (
    SELECT id FROM public.members WHERE user_id = auth.uid()
  ));

DROP POLICY IF EXISTS member_orders_own ON public.member_orders;
CREATE POLICY member_orders_own ON public.member_orders
  FOR SELECT TO authenticated
  USING (member_id IN (
    SELECT id FROM public.members WHERE user_id = auth.uid()
  ));

DROP POLICY IF EXISTS member_orders_insert_own ON public.member_orders;
CREATE POLICY member_orders_insert_own ON public.member_orders
  FOR INSERT TO authenticated
  WITH CHECK (member_id IN (
    SELECT id FROM public.members WHERE user_id = auth.uid()
  ));

GRANT SELECT ON public.products, public.lessons TO anon, authenticated;
GRANT SELECT ON public.members, public.member_wallets, public.member_point_transactions,
  public.member_orders TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.products, public.lessons,
  public.members, public.member_wallets, public.member_point_transactions,
  public.member_orders TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
