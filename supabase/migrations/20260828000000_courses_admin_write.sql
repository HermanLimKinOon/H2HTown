-- Courses admin control for h2hadmin.
--
-- Two things the admin panel needs that the schema does not provide yet:
--   1. `courses.id` has no default, so INSERT from the client fails. `products.id`
--      is GENERATED ALWAYS AS IDENTITY; courses was seeded with hand-picked ids
--      matching the webapp mock data, so use BY DEFAULT to keep explicit ids legal.
--   2. RLS on `courses` and `lessons` only allows public SELECT. Admins need write.
--
-- Safe to run more than once.

-- 1. Give courses.id a sequence, starting past whatever is already in the table.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute
    WHERE attrelid = 'public.courses'::regclass
      AND attname = 'id'
      AND attidentity <> ''
  ) THEN
    ALTER TABLE public.courses
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

    PERFORM setval(
      pg_get_serial_sequence('public.courses', 'id'),
      COALESCE((SELECT MAX(id) FROM public.courses), 0) + 1,
      false
    );
  END IF;
END $$;

-- 2. Admin write access. `is_admin()` already exists and is what the admin app
--    calls to gate the whole panel.
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.courses TO "authenticated";
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.lessons TO "authenticated";
-- Identity columns don't strictly need sequence privileges, but grant them by
-- looked-up name so this doesn't depend on the sequences being named as expected.
DO $$
DECLARE
  seq text;
BEGIN
  FOREACH seq IN ARRAY ARRAY[
    pg_get_serial_sequence('public.courses', 'id'),
    pg_get_serial_sequence('public.lessons', 'id')
  ] LOOP
    IF seq IS NOT NULL THEN
      EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO "authenticated"', seq);
    END IF;
  END LOOP;
END $$;

DROP POLICY IF EXISTS "courses_admin_write" ON public.courses;
CREATE POLICY "courses_admin_write" ON public.courses
  FOR ALL
  TO "authenticated"
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "lessons_admin_write" ON public.lessons;
CREATE POLICY "lessons_admin_write" ON public.lessons
  FOR ALL
  TO "authenticated"
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- 3. Deleting a course should take its lessons with it. The remote FK was created
--    without ON DELETE CASCADE.
ALTER TABLE public.lessons
  DROP CONSTRAINT IF EXISTS lessons_course_id_fkey;
ALTER TABLE public.lessons
  ADD CONSTRAINT lessons_course_id_fkey
  FOREIGN KEY (course_id) REFERENCES public.courses(id) ON DELETE CASCADE;
