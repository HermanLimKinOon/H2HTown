-- Products admin control for h2hadmin.
--
-- `products` has RLS enabled with a single policy, `products_public_read`
-- (SELECT only), and table grants give write access to `service_role` only
-- (see 20260827062700_fix_rls_table_grants.sql). So an admin signed into the
-- h2hadmin panel can list products but every INSERT/UPDATE/DELETE fails with a
-- row-level-security / permission error ("fail to save product").
--
-- The 20260828000000_courses_admin_write migration fixed exactly this for
-- `courses` and `lessons`; it was never done for `products`. This mirrors it.
--
-- `products.id` is already GENERATED BY DEFAULT AS IDENTITY, so unlike courses
-- there is no sequence/default to add here.
--
-- Safe to run more than once.

-- Admin write access. `is_admin()` (20260827063000_admin_emails_and_is_admin.sql)
-- is the same gate the admin app uses for the whole panel.
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.products TO "authenticated";

-- Identity columns don't strictly need sequence privileges, but grant them by
-- looked-up name so this doesn't depend on the sequence being named as expected.
DO $$
DECLARE
  seq text := pg_get_serial_sequence('public.products', 'id');
BEGIN
  IF seq IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO "authenticated"', seq);
  END IF;
END $$;

DROP POLICY IF EXISTS "products_admin_write" ON public.products;
CREATE POLICY "products_admin_write" ON public.products
  FOR ALL
  TO "authenticated"
  USING (public.is_admin())
  WITH CHECK (public.is_admin());
