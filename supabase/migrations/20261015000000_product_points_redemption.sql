-- Product checkout point redemption. Pending orders reserve points; the wallet
-- is charged only when the payment confirmation moves the order to completed.

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS points_redemption_allowed boolean NOT NULL DEFAULT true;

ALTER TABLE public.member_orders
  ADD COLUMN IF NOT EXISTS subtotal_amount integer,
  ADD COLUMN IF NOT EXISTS points_redeemed integer NOT NULL DEFAULT 0
    CHECK (points_redeemed >= 0);

ALTER TABLE public.member_point_transactions
  ADD COLUMN IF NOT EXISTS points_redeemed integer NOT NULL DEFAULT 0
    CHECK (points_redeemed >= 0);

ALTER TABLE public.member_point_transactions
  ADD COLUMN IF NOT EXISTS expires_at timestamptz;
UPDATE public.member_point_transactions
SET expires_at = created_at + interval '12 months'
WHERE expires_at IS NULL AND points_earned > 0;

ALTER TABLE public.member_orders
  ADD COLUMN IF NOT EXISTS points_refunded_at timestamptz;
ALTER TABLE public.member_orders DROP CONSTRAINT IF EXISTS member_orders_status_check;
ALTER TABLE public.member_orders ADD CONSTRAINT member_orders_status_check
  CHECK (status = ANY (ARRAY['completed'::text, 'pending'::text, 'cancelled'::text,
                            'failed'::text, 'expired'::text, 'refunded'::text]));

-- Preserve which earned-point balances a redemption used, including their
-- original expiration dates, so eligible points can be restored on a return.
CREATE TABLE IF NOT EXISTS public.member_point_redemption_allocations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.member_orders(id) ON DELETE CASCADE,
  source_transaction_id bigint NOT NULL REFERENCES public.member_point_transactions(id),
  points integer NOT NULL CHECK (points > 0),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, source_transaction_id)
);

ALTER TABLE public.member_point_redemption_allocations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.member_point_redemption_allocations FROM public, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.member_point_redemption_allocations TO service_role;

-- Carry forward any legacy balance that has no corresponding earning ledger row.
INSERT INTO public.member_point_transactions
  (member_id, type, points_earned, description, expires_at)
SELECT w.member_id, 'legacy_balance',
       GREATEST(w.points_balance - COALESCE(t.earned, 0), 0),
       'Carried forward points balance', now() + interval '12 months'
FROM public.member_wallets w
LEFT JOIN LATERAL (
  SELECT sum(points_earned)::integer AS earned
  FROM public.member_point_transactions
  WHERE member_id = w.member_id AND points_earned > 0
) t ON true
WHERE w.points_balance > COALESCE(t.earned, 0);

CREATE OR REPLACE FUNCTION public.set_point_expiry()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.points_earned > 0 AND NEW.expires_at IS NULL THEN
    NEW.expires_at := COALESCE(NEW.created_at, now()) + interval '12 months';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS member_point_transactions_set_expiry ON public.member_point_transactions;
CREATE TRIGGER member_point_transactions_set_expiry
  BEFORE INSERT ON public.member_point_transactions
  FOR EACH ROW EXECUTE FUNCTION public.set_point_expiry();

CREATE OR REPLACE FUNCTION public.create_product_order_with_points(
  p_member_id bigint,
  p_product_id bigint,
  p_points_to_redeem integer DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_product public.products%rowtype;
  v_wallet public.member_wallets%rowtype;
  v_points integer := COALESCE(p_points_to_redeem, 0);
  v_available integer;
  v_max_points integer;
  v_order_id bigint;
  v_lot_available integer;
  v_points_left integer;
  v_source record;
  v_take integer;
BEGIN
  IF v_points < 0 THEN
    RETURN jsonb_build_object('error', 'invalid_points');
  END IF;

  SELECT * INTO v_product FROM public.products
  WHERE id = p_product_id AND active = true;
  IF NOT FOUND OR v_product.member_price IS NULL OR v_product.member_price <= 0 THEN
    RETURN jsonb_build_object('error', 'product_unavailable');
  END IF;

  IF v_points > 0 AND NOT v_product.points_redemption_allowed THEN
    RETURN jsonb_build_object('error', 'promotion_not_eligible');
  END IF;

  INSERT INTO public.member_wallets (member_id, points_balance)
  VALUES (p_member_id, 0)
  ON CONFLICT (member_id) DO NOTHING;
  SELECT * INTO v_wallet FROM public.member_wallets
  WHERE member_id = p_member_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'member_not_found');
  END IF;

  SELECT COALESCE(sum(GREATEST(t.points_earned - COALESCE(a.used, 0), 0)), 0)::integer
  INTO v_lot_available
  FROM public.member_point_transactions t
  LEFT JOIN LATERAL (
    SELECT sum(points)::integer AS used
    FROM public.member_point_redemption_allocations
    WHERE source_transaction_id = t.id
  ) a ON true
  WHERE t.member_id = p_member_id AND t.points_earned > 0
    AND t.expires_at > now();
  v_available := LEAST(v_wallet.points_balance, v_lot_available);
  v_max_points := LEAST(v_available, floor(v_product.member_price / 200.0)::integer);

  IF v_points > 0 AND v_points < 10 THEN
    RETURN jsonb_build_object('error', 'minimum_redemption', 'minimum', 10);
  END IF;
  IF v_points > v_available THEN
    RETURN jsonb_build_object('error', 'insufficient_points', 'available', v_available);
  END IF;
  IF v_points > floor(v_product.member_price / 200.0)::integer THEN
    RETURN jsonb_build_object('error', 'redemption_limit_exceeded', 'maximum', floor(v_product.member_price / 200.0)::integer);
  END IF;

  INSERT INTO public.member_orders (
    member_id, order_type, item_id, item_name, subtotal_amount, amount,
    points_redeemed, currency, status, provider
  ) VALUES (
    p_member_id, 'product', v_product.id::integer, v_product.name,
    v_product.member_price, v_product.member_price - (v_points * 100),
    v_points, 'MYR', 'pending', 'revenue_monster'
  ) RETURNING id INTO v_order_id;

  -- Allocate the earliest-expiring point grants first (FEFO). Pending orders
  -- also hold allocations, so concurrent checkouts cannot spend the same lot.
  v_points_left := v_points;
  FOR v_source IN
    SELECT t.id, t.points_earned, t.expires_at,
           COALESCE(a.used, 0)::integer AS used
    FROM public.member_point_transactions t
    LEFT JOIN LATERAL (
      SELECT sum(points)::integer AS used
      FROM public.member_point_redemption_allocations
      WHERE source_transaction_id = t.id
    ) a ON true
    WHERE t.member_id = p_member_id AND t.points_earned > 0
      AND t.expires_at > now()
      AND t.points_earned > COALESCE(a.used, 0)
    ORDER BY t.expires_at ASC, t.id ASC
  LOOP
    EXIT WHEN v_points_left = 0;
    v_take := LEAST(v_points_left, v_source.points_earned - v_source.used);
    INSERT INTO public.member_point_redemption_allocations
      (order_id, source_transaction_id, points, expires_at)
    VALUES (v_order_id, v_source.id, v_take, v_source.expires_at);
    v_points_left := v_points_left - v_take;
  END LOOP;

  IF v_points_left > 0 THEN
    DELETE FROM public.member_orders WHERE id = v_order_id;
    RETURN jsonb_build_object('error', 'points_balance_unavailable');
  END IF;

  RETURN jsonb_build_object(
    'order_id', v_order_id,
    'subtotal_amount', v_product.member_price,
    'amount', v_product.member_price - (v_points * 100),
    'points_redeemed', v_points,
    'available_points', v_available,
    'maximum_points', v_max_points
  );
END;
$$;

REVOKE ALL ON FUNCTION public.create_product_order_with_points(bigint, bigint, integer)
  FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_product_order_with_points(bigint, bigint, integer)
  TO service_role;

CREATE OR REPLACE FUNCTION public.debit_product_order_points()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_balance integer;
BEGIN
  IF OLD.status = 'pending' AND NEW.status = 'completed'
     AND NEW.order_type = 'product' AND NEW.points_redeemed > 0 THEN
    SELECT points_balance INTO v_balance
    FROM public.member_wallets WHERE member_id = NEW.member_id FOR UPDATE;
    IF NOT FOUND OR v_balance < NEW.points_redeemed THEN
      RAISE EXCEPTION 'Insufficient points to complete order %', NEW.id;
    END IF;

    UPDATE public.member_wallets
    SET points_balance = points_balance - NEW.points_redeemed
    WHERE member_id = NEW.member_id;

    INSERT INTO public.member_point_transactions
      (member_id, type, points_earned, points_redeemed, description)
    VALUES
      (NEW.member_id, 'redemption', 0, NEW.points_redeemed,
       'Redeemed on product order #' || NEW.id);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS member_orders_debit_product_points ON public.member_orders;
CREATE TRIGGER member_orders_debit_product_points
  BEFORE UPDATE OF status ON public.member_orders
  FOR EACH ROW EXECUTE FUNCTION public.debit_product_order_points();

CREATE OR REPLACE FUNCTION public.release_failed_product_point_reservations()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF OLD.status = 'pending' AND NEW.status NOT IN ('pending', 'completed') THEN
    DELETE FROM public.member_point_redemption_allocations WHERE order_id = NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS member_orders_release_point_reservations ON public.member_orders;
CREATE TRIGGER member_orders_release_point_reservations
  AFTER UPDATE OF status ON public.member_orders
  FOR EACH ROW EXECUTE FUNCTION public.release_failed_product_point_reservations();

-- Call only after the associated product order's monetary refund is confirmed.
-- The RPC restores each redeemed point to its source expiry; already-expired
-- points are not credited back.
CREATE OR REPLACE FUNCTION public.refund_product_order_points(p_order_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order public.member_orders%rowtype;
  v_restore integer := 0;
  v_allocation record;
BEGIN
  SELECT * INTO v_order FROM public.member_orders
  WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND OR v_order.order_type <> 'product' THEN
    RETURN jsonb_build_object('error', 'product_order_not_found');
  END IF;
  IF v_order.points_refunded_at IS NOT NULL THEN
    RETURN jsonb_build_object('status', 'already_refunded', 'points_restored', 0);
  END IF;
  IF v_order.status <> 'completed' THEN
    RETURN jsonb_build_object('error', 'order_not_completed');
  END IF;

  PERFORM 1 FROM public.member_wallets WHERE member_id = v_order.member_id FOR UPDATE;
  FOR v_allocation IN
    SELECT a.points, a.expires_at
    FROM public.member_point_redemption_allocations a
    WHERE a.order_id = v_order.id AND a.expires_at > now()
  LOOP
    UPDATE public.member_wallets
    SET points_balance = points_balance + v_allocation.points
    WHERE member_id = v_order.member_id;
    INSERT INTO public.member_point_transactions
      (member_id, type, points_earned, description, expires_at)
    VALUES
      (v_order.member_id, 'redemption_refund', v_allocation.points,
       'Returned points for product order #' || v_order.id, v_allocation.expires_at);
    v_restore := v_restore + v_allocation.points;
  END LOOP;

  UPDATE public.member_orders
  SET status = 'refunded', points_refunded_at = now()
  WHERE id = v_order.id;

  RETURN jsonb_build_object('status', 'refunded', 'points_restored', v_restore);
END;
$$;

REVOKE ALL ON FUNCTION public.refund_product_order_points(bigint)
  FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.refund_product_order_points(bigint)
  TO service_role;

COMMENT ON COLUMN public.member_orders.subtotal_amount IS
  'Product price before point redemption, stored in sen.';
COMMENT ON COLUMN public.member_orders.points_redeemed IS
  'Points reserved on a pending product order and deducted only when payment is confirmed.';
COMMENT ON COLUMN public.products.points_redemption_allowed IS
  'Set false for promotions that cannot be combined with point redemption.';
