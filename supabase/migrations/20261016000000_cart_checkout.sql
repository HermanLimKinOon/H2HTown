-- Store individual cart lines under one payment/order record and reserve
-- reward points atomically for the complete cart subtotal.

CREATE TABLE IF NOT EXISTS public.member_order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.member_orders(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id),
  product_name text NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_amount integer NOT NULL CHECK (unit_amount > 0),
  line_amount integer NOT NULL CHECK (line_amount > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, product_id)
);

ALTER TABLE public.member_order_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.member_order_items FROM public, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.member_order_items TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.member_order_items_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.create_product_cart_order_with_points(
  p_member_id bigint,
  p_items jsonb,
  p_points_to_redeem integer DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_points integer := COALESCE(p_points_to_redeem, 0);
  v_available integer;
  v_max_points integer;
  v_order_id bigint;
  v_first_product_id bigint;
  v_item_count integer;
  v_subtotal bigint;
  v_cart_name text;
  v_lot_available integer;
  v_points_left integer;
  v_source record;
  v_take integer;
  v_line record;
BEGIN
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0
     OR jsonb_array_length(p_items) > 50 THEN
    RETURN jsonb_build_object('error', 'invalid_cart');
  END IF;
  IF v_points < 0 THEN
    RETURN jsonb_build_object('error', 'invalid_points');
  END IF;

  SELECT count(*)::integer, count(DISTINCT x.product_id)::integer,
         min(x.product_id),
         sum(p.member_price::bigint * x.quantity),
         string_agg(p.name || CASE WHEN x.quantity > 1 THEN ' x' || x.quantity ELSE '' END, ', ' ORDER BY p.id)
  INTO v_item_count, v_available, v_first_product_id, v_subtotal, v_cart_name
  FROM jsonb_to_recordset(p_items) AS x(product_id bigint, quantity integer)
  JOIN public.products p ON p.id = x.product_id AND p.active = true
  WHERE x.product_id IS NOT NULL AND x.quantity BETWEEN 1 AND 99
    AND p.member_price IS NOT NULL AND p.member_price > 0;

  IF v_item_count = 0 OR v_item_count <> jsonb_array_length(p_items)
     OR v_item_count <> v_available THEN
    RETURN jsonb_build_object('error', 'product_unavailable_or_duplicate');
  END IF;
  IF v_subtotal > 2147483647 THEN
    RETURN jsonb_build_object('error', 'cart_total_too_large');
  END IF;
  IF v_points > 0 AND EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS x(product_id bigint, quantity integer)
    JOIN public.products p ON p.id = x.product_id
    WHERE NOT p.points_redemption_allowed
  ) THEN
    RETURN jsonb_build_object('error', 'promotion_not_eligible');
  END IF;

  INSERT INTO public.member_wallets (member_id, points_balance)
  VALUES (p_member_id, 0)
  ON CONFLICT (member_id) DO NOTHING;
  PERFORM 1 FROM public.member_wallets WHERE member_id = p_member_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'member_not_found');
  END IF;

  SELECT COALESCE(sum(GREATEST(t.points_earned - COALESCE(a.used, 0), 0)), 0)::integer
  INTO v_lot_available
  FROM public.member_point_transactions t
  LEFT JOIN LATERAL (
    SELECT sum(points)::integer AS used
    FROM public.member_point_redemption_allocations
    WHERE source_transaction_id = t.id
  ) a ON true
  WHERE t.member_id = p_member_id AND t.points_earned > 0 AND t.expires_at > now();
  SELECT LEAST(w.points_balance, v_lot_available) INTO v_available
  FROM public.member_wallets w WHERE w.member_id = p_member_id;
  v_max_points := LEAST(v_available, floor(v_subtotal / 200.0)::integer);

  IF v_points > 0 AND v_points < 10 THEN
    RETURN jsonb_build_object('error', 'minimum_redemption', 'minimum', 10);
  END IF;
  IF v_points > v_available THEN
    RETURN jsonb_build_object('error', 'insufficient_points', 'available', v_available);
  END IF;
  IF v_points > floor(v_subtotal / 200.0)::integer THEN
    RETURN jsonb_build_object('error', 'redemption_limit_exceeded', 'maximum', floor(v_subtotal / 200.0)::integer);
  END IF;

  INSERT INTO public.member_orders (
    member_id, order_type, item_id, item_name, subtotal_amount, amount,
    points_redeemed, currency, status, provider
  ) VALUES (
    p_member_id, 'product', v_first_product_id::integer,
    'Cart (' || v_item_count || ' items): ' || left(v_cart_name, 180),
    v_subtotal::integer, (v_subtotal - v_points * 100)::integer,
    v_points, 'MYR', 'pending', 'revenue_monster'
  ) RETURNING id INTO v_order_id;

  FOR v_line IN
    SELECT p.id, p.name, p.member_price::integer AS unit_amount, x.quantity
    FROM jsonb_to_recordset(p_items) AS x(product_id bigint, quantity integer)
    JOIN public.products p ON p.id = x.product_id AND p.active = true
    ORDER BY p.id
  LOOP
    INSERT INTO public.member_order_items
      (order_id, product_id, product_name, quantity, unit_amount, line_amount)
    VALUES
      (v_order_id, v_line.id, v_line.name, v_line.quantity,
       v_line.unit_amount, (v_line.unit_amount::bigint * v_line.quantity)::integer);
  END LOOP;

  -- Allocate the earliest-expiring grants first, reserving them for this order.
  v_points_left := v_points;
  FOR v_source IN
    SELECT t.id, t.points_earned, t.expires_at, COALESCE(a.used, 0)::integer AS used
    FROM public.member_point_transactions t
    LEFT JOIN LATERAL (
      SELECT sum(points)::integer AS used
      FROM public.member_point_redemption_allocations
      WHERE source_transaction_id = t.id
    ) a ON true
    WHERE t.member_id = p_member_id AND t.points_earned > 0
      AND t.expires_at > now() AND t.points_earned > COALESCE(a.used, 0)
    ORDER BY t.expires_at ASC, t.id ASC
  LOOP
    EXIT WHEN v_points_left = 0;
    v_take := LEAST(v_points_left, v_source.points_earned - v_source.used);
    INSERT INTO public.member_point_redemption_allocations
      (order_id, source_transaction_id, points, expires_at)
    VALUES (v_order_id, v_source.id, v_take, v_source.expires_at);
    v_points_left := v_points_left - v_take;
  END LOOP;

  IF v_points_left > 0 THEN
    DELETE FROM public.member_orders WHERE id = v_order_id;
    RETURN jsonb_build_object('error', 'points_balance_unavailable');
  END IF;

  RETURN jsonb_build_object(
    'order_id', v_order_id,
    'item_name', 'Cart (' || v_item_count || ' items)',
    'subtotal_amount', v_subtotal,
    'amount', v_subtotal - v_points * 100,
    'points_redeemed', v_points,
    'available_points', v_available,
    'maximum_points', v_max_points
  );
END;
$$;

REVOKE ALL ON FUNCTION public.create_product_cart_order_with_points(bigint, jsonb, integer)
  FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_product_cart_order_with_points(bigint, jsonb, integer)
  TO service_role;
