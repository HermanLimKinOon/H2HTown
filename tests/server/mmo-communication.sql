 perform set_config('request.jwt.claim.sub',b::text,true);r:=public.mmo_history('party');perform pg_temp.check_ok(jsonb_array_length(r)=1,'party delivery');
 reset role;update private.mmo_players set social_at='-infinity' where id=b;
 set local role authenticated;perform pg_temp.check_ok(pg_temp.denied(format('select public.mmo_social(''kick'',''party'',%L,null,%L)',a,gid)),'member cannot kick owner');
 perform public.mmo_social('leave','party',null,null,gid);
 perform pg_temp.check_ok(pg_temp.denied('select public.mmo_history(''party'')'),'history denied after leave');
 perform pg_temp.check_ok(pg_temp.denied('select public.mmo_send(''party'',''outsider'',gen_random_uuid())'),'send denied after leave');
 reset role;
 update private.mmo_players set seen=clock_timestamp()-interval '16 seconds' where id=a;
 perform set_config('request.jwt.claim.sub',a::text,true);set local role authenticated;
 perform pg_temp.check_ok(pg_temp.denied('select public.mmo_send(''local'',''stale'',gen_random_uuid())'),'stale position rejected');
 reset role;
 update private.mmo_players set x=-11,z=-4,budget=3,moved=clock_timestamp(),seen=clock_timestamp() where id=a;
